export function schoolDiscountText(
  locale: string,
  key: SchoolDiscountCopyKey,
  values: Record<string, string | number> = {},
): string {
  const copy = schoolDiscountCopy[locale] || schoolDiscountCopy.en;
  return copy[key].replace(/\{([^}]+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder);
}

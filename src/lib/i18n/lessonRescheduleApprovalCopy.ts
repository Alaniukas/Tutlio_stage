export function lessonRescheduleApprovalText(
  locale: string, key: LessonRescheduleApprovalCopyKey, values: Record<string, string> = {},
): string {
  const copy = lessonRescheduleApprovalCopy[locale] || lessonRescheduleApprovalCopy.en;
  return copy[keys.indexOf(key)].replace(/\{([^}]+)\}/g, (placeholder, name: string) => values[name] ?? placeholder);
}

export function lessonRescheduleApprovalErrorKey(code: string): LessonRescheduleApprovalCopyKey {
  const errors: Record<string, LessonRescheduleApprovalCopyKey> = {
    reschedule_conflict: 'conflict', reschedule_changed: 'changed', reschedule_expired: 'expired',
    reschedule_no_contact: 'noContact', reschedule_pending: 'alreadyPending', reschedule_email_failed: 'sendFailed',
  };
  return errors[code] || 'error';
}

create or replace function public.match_in_app_support_knowledge(
  query_embedding extensions.vector(1536),
  match_threshold double precision,
  match_count integer,
  filter_portal text,
  filter_entity_type text,
  filter_organization_id uuid,
  filter_feature_ids text[],
  filter_permissions text[]
)
returns table (
  knowledge_key text,
  title text,
  content text,
  similarity double precision
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select
    knowledge.knowledge_key,
    knowledge.title,
    knowledge.content,
    (1 - (knowledge.embedding <=> query_embedding))::double precision as similarity
  from public.in_app_support_knowledge as knowledge
  where knowledge.is_active = true
    and (cardinality(knowledge.portals) = 0 or filter_portal = any(knowledge.portals))
    and (
      cardinality(knowledge.entity_types) = 0
      or (filter_entity_type is not null and filter_entity_type = any(knowledge.entity_types))
    )
    and (knowledge.organization_id is null or knowledge.organization_id = filter_organization_id)
    and (knowledge.feature_id is null or knowledge.feature_id = any(coalesce(filter_feature_ids, '{}'::text[])))
    and (
      knowledge.required_permission is null
      or knowledge.required_permission = any(coalesce(filter_permissions, '{}'::text[]))
    )
    and 1 - (knowledge.embedding <=> query_embedding) >= match_threshold
  order by knowledge.embedding <=> query_embedding
  limit least(greatest(match_count, 1), 8);
$$;

create or replace function public.match_in_app_support_memory(
  query_embedding extensions.vector(1536),
  match_threshold double precision,
  match_count integer,
  filter_user_id uuid,
  filter_conversation_id text,
  filter_organization_id uuid
)
returns table (
  id bigint,
  content text,
  similarity double precision
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select
    memory.id,
    memory.content,
    (1 - (memory.embedding <=> query_embedding))::double precision as similarity
  from public.in_app_support_memory as memory
  where memory.user_id = filter_user_id
    and memory.conversation_id = filter_conversation_id
    and memory.organization_id is not distinct from filter_organization_id
    and memory.expires_at > now()
    and 1 - (memory.embedding <=> query_embedding) >= match_threshold
  order by memory.embedding <=> query_embedding
  limit least(greatest(match_count, 1), 8);
$$;


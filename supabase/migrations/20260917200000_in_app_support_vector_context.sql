create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists public.in_app_support_knowledge (
  id bigint generated by default as identity primary key,
  knowledge_key text not null unique,
  title text not null,
  content text not null,
  locale text not null default 'multi',
  portals text[] not null default '{}',
  entity_types text[] not null default '{}',
  feature_id text,
  required_permission text,
  organization_id uuid references public.organizations(id) on delete cascade,
  metadata jsonb not null default '{}'::jsonb,
  embedding extensions.vector(1536) not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint in_app_support_knowledge_portals check (
    portals <@ array['tutor', 'organization', 'student', 'parent']::text[]
  ),
  constraint in_app_support_knowledge_entity_types check (
    entity_types <@ array['company', 'school']::text[]
  )
);

create table if not exists public.in_app_support_memory (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id text not null,
  organization_id uuid references public.organizations(id) on delete cascade,
  portal text not null,
  content text not null,
  content_hash text not null,
  embedding extensions.vector(1536) not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  constraint in_app_support_memory_portal check (
    portal in ('tutor', 'organization', 'student', 'parent')
  ),
  constraint in_app_support_memory_conversation_length check (
    char_length(conversation_id) between 8 and 100
  ),
  constraint in_app_support_memory_content_length check (
    char_length(content) between 1 and 8000
  ),
  unique (user_id, conversation_id, content_hash)
);

comment on table public.in_app_support_knowledge is
  'Server-only support documentation. Optional function chunks are tagged so authorization filters run before vector ranking.';
comment on table public.in_app_support_memory is
  'Short-lived semantic memory scoped to one signed-in user, support conversation, and exact organization.';

